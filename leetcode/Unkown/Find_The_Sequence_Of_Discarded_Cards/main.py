for v in range(N):
    q.put(v + 1)
discarded = []
if q.qsize() <= 1:
    print("Discarded cards: ", [])
    if q.empty() == False:
        print(f"Remaining card: ", q.get(False))
else:
    while True:
        discarded.append(q.get(False))
        secondItem = q.get(False)
        if q.empty():
            print("Discarded cards: ", discarded)
            print(f"Remaining card: ", secondItem)
            break
        q.put(secondItem)


